#!/usr/bin/env python3
"""Rebuild the voice corpus with provenance. Assumes AI unless proven otherwise."""
import json, glob, os, re

ROOT = os.path.dirname(os.path.abspath(__file__))
RAW  = os.path.join(ROOT, "raw")
OUT  = os.path.join(ROOT, "corpus")

AI_TAGS = ["generated by ai", "🤖", "co-authored-by: claude", "co-authored-by: codex", "claude code", "written by ai"]

def words(t): return len(re.findall(r"\S+", t or ""))
def tagged(b):
    b = (b or "").lower()
    return any(t in b for t in AI_TAGS)

def write(name, chunks):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    open(path, "w").write("\n\n---\n\n".join(c.strip() for c in chunks if c.strip()))
    return words(open(path).read())

def load(pattern):
    items = []
    for f in glob.glob(os.path.join(RAW, pattern)):
        try: items += json.load(open(f))
        except Exception: pass
    seen, uniq = set(), []
    for x in items:
        k = x.get("n") or x.get("sha")
        if k in seen: continue
        seen.add(k); uniq.append(x)
    return uniq

prs = load("prs*.json")
old  = [p for p in prs if (p["at"] or "")[:4] in ("2020", "2021")]
new  = [p for p in prs if (p["at"] or "")[:4] == "2026"]

manifest = {}

manifest["pr_description_2020.md"] = {
    "words": write("pr_description_2020.md",
                   [f"## #{p['n']} {p['title']} ({p['at'][:10]})\n\n{p['body']}" for p in old]),
    "provenance": "GitHub PR bodies authored by bostondv, 2020-2021",
    "ai_likelihood": "human",
    "note": "Pre-agent era. Typed by him, but 4-6 years old: register may have moved.",
}

manifest["slack.md"] = {
    "words": write("slack.md", [open(os.path.join(RAW, "slack.md")).read()]),
    "provenance": "60 Slack replies from public channels, plus DMs he approved reading",
    "ai_likelihood": "human",
    "note": "Typed live. Short-form, so it says more about register than structure.",
}

manifest["corrections.md"] = {
    "words": write("corrections.md", [open(os.path.join(RAW, "corrections.md")).read()]),
    "provenance": "His own words when correcting assistant output, this thread and prior ones",
    "ai_likelihood": "human",
    "note": "Highest fidelity: each line is a place assistant output missed.",
}

ai_tagged = [p for p in new if tagged(p["body"])]
manifest["pr_description_2026_ai.md"] = {
    "words": write("pr_description_2026_ai.md",
                   [f"## #{p['n']} {p['title']} ({p['at'][:10]})\n\n{p['body']}" for p in ai_tagged]),
    "provenance": f"{len(ai_tagged)} of {len(new)} 2026 PR bodies carrying an explicit AI tag",
    "ai_likelihood": "ai",
    "note": "Excluded from voice math. Kept only to measure drift.",
}

manifest["pr_description_2026_untagged.md"] = {
    "words": write("pr_description_2026_untagged.md",
                   [f"## #{p['n']} {p['title']} ({p['at'][:10]})\n\n{p['body']}" for p in new if not tagged(p["body"])][:60]),
    "provenance": "Sample of 2026 PR bodies with no AI tag",
    "ai_likelihood": "mixed",
    "note": "Assume AI, lightly edited. 'Approved by him', not 'written by him'.",
}

manifest["commits.md"] = {
    "words": 0,
    "provenance": "excluded — all AI-authored",
    "ai_likelihood": "ai",
    "note": "Boston confirmed commit messages are all AI. Not harvested.",
}

json.dump(manifest, open(os.path.join(ROOT, "manifest.json"), "w"), indent=2)
human = sum(v["words"] for v in manifest.values() if v["ai_likelihood"] == "human")
total = sum(v["words"] for v in manifest.values())
for k, v in manifest.items():
    print(f"{k:34} {v['words']:>7}  {v['ai_likelihood']}")
print(f"{'human total':34} {human:>7} of {total}")
